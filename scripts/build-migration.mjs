/**
 * Concatenates every migration into one file to paste into the Supabase SQL
 * editor, so setting up a database is one paste rather than nine.
 *
 * The whole thing runs in a single transaction: if any statement fails, none
 * of it is applied and the database is left as it was, rather than half
 * migrated with no record of how far it got.
 *
 *   node scripts/build-migration.mjs        # writes supabase/all-migrations.sql
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const DIR = "supabase/migrations";
const OUT = "supabase/all-migrations.sql";

const files = readdirSync(DIR)
  .filter((f) => f.endsWith(".sql"))
  .sort();

if (!files.length) {
  console.error(`No migrations found in ${DIR}`);
  process.exit(1);
}

const parts = [
  `-- Gridiron Legacy — the whole schema, in order.
--
-- Generated by scripts/build-migration.mjs. Do not edit this file; edit the
-- migrations it is built from and run the script again.
--
-- Paste the whole thing into the Supabase SQL editor and run it once. It is
-- wrapped in a transaction, so a failure anywhere leaves the database
-- untouched rather than half migrated.
--
-- Built from ${files.length} migrations:
${files.map((f) => `--   ${f}`).join("\n")}

begin;
`,
];

for (const file of files) {
  const sql = readFileSync(path.join(DIR, file), "utf8").trimEnd();
  parts.push(`
-- ${"=".repeat(70)}
-- ${file}
-- ${"=".repeat(70)}

${sql}
`);
}

parts.push(`
commit;

-- If this ran without error, the schema is in place. Next: seed the league.
--
--   node scripts/seed.mjs --teams 12
`);

writeFileSync(OUT, parts.join("\n"));

const lines = parts.join("\n").split("\n").length;
console.log(`Wrote ${OUT} — ${files.length} migrations, ${lines} lines.`);
console.log("Paste it into the Supabase SQL editor and run it once.");
