/**
 * Concatenates every migration into one file to paste into the Supabase SQL
 * editor, so setting up a database is one paste rather than ten.
 *
 * Each migration is recorded in a schema_migrations table and skipped if it is
 * already there, so the file can be run again after new migrations are added
 * without failing on the tables the first run created. That matters: the
 * obvious version of this file aborts on "relation already exists" the moment
 * anything has been applied, which is exactly when you need to add one.
 *
 * The whole run is one transaction, so a failure anywhere leaves the database
 * as it was rather than half migrated.
 *
 *   node scripts/build-migration.mjs        # writes supabase/all-migrations.sql
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const DIR = "supabase/migrations";
const OUT = "supabase/all-migrations.sql";

// The dollar tag wrapping each migration. Migrations quote function bodies
// with $$, so the wrapper needs its own tag or the nesting collapses.
const TAG = "$__migration__$";

const files = readdirSync(DIR)
  .filter((f) => f.endsWith(".sql"))
  .sort();

if (!files.length) {
  console.error(`No migrations found in ${DIR}`);
  process.exit(1);
}

for (const file of files) {
  if (readFileSync(path.join(DIR, file), "utf8").includes(TAG)) {
    console.error(`${file} contains ${TAG}, which this script uses to wrap it.`);
    process.exit(1);
  }
}

const parts = [
  `-- Gridiron Legacy — the whole schema, in order.
--
-- Generated by scripts/build-migration.mjs. Do not edit this file; edit the
-- migrations in supabase/migrations and run the script again.
--
-- Paste the whole thing into the Supabase SQL editor and run it. Safe to run
-- again later: each migration is recorded once applied and skipped after
-- that, so adding a migration means re-running this file, not hunting for
-- which ones are new.
--
-- Built from ${files.length} migrations:
${files.map((f) => `--   ${f}`).join("\n")}

begin;

-- What has already been applied. Created first, so the very first run of this
-- file records itself.
create table if not exists schema_migrations (
  name        text primary key,
  applied_at  timestamptz not null default now()
);
`,
];

for (const file of files) {
  const sql = readFileSync(path.join(DIR, file), "utf8").trimEnd();

  parts.push(`
-- ${"=".repeat(70)}
-- ${file}
-- ${"=".repeat(70)}

do ${TAG}
begin
  if exists (select 1 from schema_migrations where name = '${file}') then
    raise notice 'skipping %, already applied', '${file}';
  else
${sql
  .split("\n")
  .map((line) => (line.trim() ? `    ${line}` : ""))
  .join("\n")}

    insert into schema_migrations (name) values ('${file}');
    raise notice 'applied %', '${file}';
  end if;
end
${TAG};
`);
}

parts.push(`
commit;

-- Which migrations this database has:
--   select name, applied_at from schema_migrations order by name;
--
-- If the schema is in place, next is the league itself:
--   supabase/seed.sql, then  select * from seed_league('Gridiron Legacy', 12);
`);

writeFileSync(OUT, parts.join("\n"));

console.log(`Wrote ${OUT} — ${files.length} migrations, re-runnable.`);
